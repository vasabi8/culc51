"""
Модуль розрахунку фінансових коефіцієнтів для Z-моделі
Версія: 2019 (17 коефіцієнтів)
v2: [V2-A1] чистий борг без обрізання до 0; [V2-B5] дохід 2220 за модулем; [V2-A2] MK17 = «не враховується» для F110=4
(див. debtor_scoring_v2_changes.md)
Постанова НБУ №351
"""

# ============================================================================
# КОНСТАНТИ ДЛЯ МАРКЕРІВ ГРАНИЧНИХ ЗНАЧЕНЬ
# ============================================================================
MARKER_FIRST_RANGE = -9999999999  # Група 1 (п.6): при знаменнику 0 береться X ПЕРШОГО діапазону (найменше значення показника)
MARKER_LAST_RANGE = 9999999999   # Група 2 (п.7): при знаменнику 0 береться X ОСТАННЬОГО діапазону (найбільше значення показника)
MARKER_ZERO = None         # Група 0: коефіцієнт не використовується (повертає WOE=0)

# Кількість коефіцієнтів у цій версії
NUM_COEFFICIENTS = 17

# Опис версії
VERSION_INFO = {
    'version': '2019',
    'description': 'Z-модель з 17 коефіцієнтами (Постанова НБУ №351, редакція 2019)',
    'num_coefficients': NUM_COEFFICIENTS,
}


def get_row_value(row, code, code2=None) -> float:
    """
    Отримання значення рядка фінансової звітності.
    
    Args:
        row: рядок даних (pd.Series)
        code: код рядка (1000, 2000, тощо)
        code2: другий код для комбінованої колонки (опціонально)
        
    Returns:
        float: значення або 0.0
        
    Приклади:
        get_row_value(row, 2240)           # шукає колонку 2240
        get_row_value(row, 2240, 2160)     # спочатку шукає "2240_2160", потім суму
        get_row_value(row, "2240_2160")    # шукає колонку "2240_2160"
    """
    # Якщо передано два коди, спробувати знайти комбіновану колонку
    if code2 is not None:
        # Спробувати різні формати імені комбінованої колонки: "2270_2165", "2270/2165"
        for sep in ['_', '/']:
            combined_name = f"{code}{sep}{code2}"
            if combined_name in row.index:
                try:
                    val = float(row[combined_name])
                    if val != 0:
                        return val
                except:
                    pass
        # Якщо комбінованої немає або вона 0, повернути суму окремих
        return get_row_value(row, code) + get_row_value(row, code2)
    
    # Якщо код є рядком з розділювачем ("_" або "/")
    if isinstance(code, str) and ('_' in code or '/' in code):
        # Спробувати обидва формати: "2270_2165" та "2270/2165"
        code_underscore = code.replace('/', '_')
        code_slash = code.replace('_', '/')
        for variant in [code, code_underscore, code_slash]:
            if variant in row.index:
                try:
                    return float(row[variant])
                except:
                    return 0.0
        return 0.0
    
    # Стандартна логіка
    for col_name in [code, str(code), float(code)]:
        if col_name in row.index:
            try:
                return float(row[col_name])
            except:
                return 0.0
    return 0.0


def safe_divide(num: float, denom: float, coef_name: str, coef_groups: dict) -> float:
    """
    Безпечне ділення з урахуванням групи коефіцієнта.
    
    Група 1 (п.6): при знам.=0 → MARKER_FIRST_RANGE (X першого діапазону)
    Група 2 (п.7): при знам.=0 → MARKER_LAST_RANGE (X останнього діапазону)
    Група 3 (п.8): при знам.<=0 → MARKER_ZERO (показник не враховується, X = 0)
    
    Args:
        num: чисельник
        denom: знаменник
        coef_name: назва коефіцієнта (K1, MK3, тощо)
        coef_groups: словник груп коефіцієнтів
        
    Returns:
        float: значення коефіцієнта або маркер
    """
    group = coef_groups.get(coef_name, 2)  # За замовчуванням група 2
    
    if group == 3:
        # Група 3: перевірка на <= 0
        if denom <= 0:
            return MARKER_ZERO
    else:
        # Групи 1 та 2: перевірка на = 0
        if denom == 0:
            return MARKER_FIRST_RANGE if group == 1 else MARKER_LAST_RANGE
    
    return num / denom


def _f110_code(row) -> str:
    """[V2-A2] Код форми звітності F110 з рядка data_FS (поле F110_form): 4, 4.0, '4' → '4'."""
    val = row.get('F110_form', '') if hasattr(row, 'get') else ''
    s = str(val).strip()
    if s.endswith('.0'):
        s = s[:-2]
    return '' if s in ('', 'nan', 'None', '0') else s


def calculate_coefficients(row, zvit: int, coef_groups: dict) -> dict:
    """
    Розрахунок всіх 17 фінансових коефіцієнтів (версія 2019).
    
    Args:
        row: рядок з фінансовою звітністю (pd.Series)
        zvit: тип звітності (1=великі/середні, 2=малі, 3=малі скорочена)
        coef_groups: словник груп коефіцієнтів з файлу констант
        
    Returns:
        dict: словник з коефіцієнтами K1-K17
    """
    coeffs = {}
    
    # Скорочення для зручності
    def get(code, code2=None):
        return get_row_value(row, code, code2)
    
    def divide(num, denom, coef_name):
        return safe_divide(num, denom, coef_name, coef_groups)
    
    # =========================================================================
    # ДОПОМІЖНІ ВЕЛИЧИНИ
    # =========================================================================
    if zvit == 1:
        # Для великих/середніх підприємств
        # NET_DEBT = X1510 + X1515 + X1600 + X1610 - X1165
        # [V2-A1] Без обрізання до 0: формула табл. 3 — (1510+1515+1600+1610−1165); для показників
        #         групи 3 від'ємний знаменник і так дає «не враховується» (safe_divide, п.8)
        net_debt = get(1510) + get(1515) + get(1600) + get(1610) - get(1165)
        # DEBT = X1510 + X1515 + X1600 + X1610
        debt = get(1510) + get(1515) + get(1600) + get(1610)
    else:
        # Для малих підприємств
        # NET_DEBT = X1595 + X1600 + X1610 - X1165
        net_debt = get(1595) + get(1600) + get(1610) - get(1165)   # [V2-A1] без обрізання до 0
        # DEBT = X1595 + X1600 + X1610
        debt = get(1595) + get(1600) + get(1610)
    
    # =========================================================================
    # X1: Частка капіталу в балансі підприємства
    # Coef_ID: Equity_ratio
    # Group: 1 (MIN_WOE)
    # Formula Big: X1495/X1300
    # Formula Small: X1495/X1300
    # =========================================================================
    if zvit == 1:
        coeffs['K1'] = divide(get(1495), get(1300), 'K1')
    else:
        coeffs['K1'] = divide(get(1495), get(1300), 'MK1')
    
    # =========================================================================
    # X2: Спроможність покривати короткострокові зобов'язання оборотними активами
    # Coef_ID: Current_ratio_2
    # Group: 2 (MAX_WOE)
    # Formula Big: (X1125+X1100+X1110+X1165)/X1695
    # Formula Small: (X1125+X1155+X1100+X1110+X1165)/X1695
    # =========================================================================
    if zvit == 1:
        coeffs['K2'] = divide(
            get(1125) + get(1100) + get(1110) + get(1165),
            get(1695), 'K2')
    else:
        coeffs['K2'] = divide(
            get(1125) + get(1155) + get(1100) + get(1110) + get(1165),
            get(1695), 'MK2')
    
    # =========================================================================
    # X3: Спроможність обслуговування боргу прибутком до оподаткування
    # Coef_ID: EBT_D
    # Group: 0 (не використовується) для Big, 3 (ZERO) для Small
    # Formula Big: 0 (не використовується)
    # Formula Small: X2290/NET_DEBT
    # =========================================================================
    if zvit == 1:
        coeffs['K3'] = MARKER_ZERO
    else:
        coeffs['K3'] = divide(get(2290), net_debt, 'MK3')
    
    # =========================================================================
    # X4: Спроможність покривати короткострокові зобов'язання високоліквідними активами
    # Coef_ID: Quick_ratio
    # Group: 1 (MIN_WOE)
    # Formula Big: (X1125+X1165)/X1695
    # Formula Small: (X1125+X1155+X1165)/X1695
    # =========================================================================
    if zvit == 1:
        coeffs['K4'] = divide(
            get(1125) + get(1165),
            get(1695), 'K4')
    else:
        coeffs['K4'] = divide(
            get(1125) + get(1155) + get(1165),
            get(1695), 'MK4')
    
    # =========================================================================
    # X5: Період повного обороту запасів
    # Coef_ID: Invent_turn
    # Group: 2 (MAX_WOE)
    # Formula Big: ((X1100+X1110)*365)/X2050
    # Formula Small: ((X1100+X1110)*365)/X2050
    # =========================================================================
    if zvit == 1:
        coeffs['K5'] = divide(
            (get(1100) + get(1110)) * 365,
            abs(get(2050)), 'K5')
    else:
        coeffs['K5'] = divide(
            (get(1100) + get(1110)) * 365,
            abs(get(2050)), 'MK5')
    
    # =========================================================================
    # X6: Спроможність обслуговування боргу валовим прибутком
    # Coef_ID: gross_profit_D
    # Group: 3 (ZERO при знам.<=0)
    # Formula Big: (X2090-X2095)/NET_DEBT
    # Formula Small: (X2000-X2050)/NET_DEBT
    # =========================================================================
    if zvit == 1:
        coeffs['K6'] = divide(
            get(2090) - abs(get(2095)),
            net_debt, 'K6')
    else:
        coeffs['K6'] = divide(
            get(2000) - abs(get(2050)),
            net_debt, 'MK6')
    
    # =========================================================================
    # X7: Частка боргу підприємства до активів
    # Coef_ID: D_A
    # Group: 2 (MAX_WOE)
    # Formula Big: DEBT/X1300
    # Formula Small: DEBT/X1300
    # =========================================================================
    if zvit == 1:
        coeffs['K7'] = divide(debt, get(1300), 'K7')
    else:
        coeffs['K7'] = divide(debt, get(1300), 'MK7')
    
    # =========================================================================
    # X8: Період повного обороту кредиторської заборгованості
    # Coef_ID: Payables_turn
    # Group: 2 (MAX_WOE)
    # Formula Big: (X1615*365)/X2050
    # Formula Small: (X1615*365)/X2050
    # =========================================================================
    if zvit == 1:
        coeffs['K8'] = divide(get(1615) * 365, abs(get(2050)), 'K8')
    else:
        coeffs['K8'] = divide(get(1615) * 365, abs(get(2050)), 'MK8')
    
    # =========================================================================
    # X9: Ефективність операційної діяльності підприємства
    # Coef_ID: EBIT_1_margin
    # Group: 1 (MIN_WOE) для Big, 0 (не використовується) для Small
    # Formula Big: (X2190-X2195)/(X2000+X2010)
    # Formula Small: 0 (не використовується)
    # =========================================================================
    if zvit == 1:
        coeffs['K9'] = divide(
            get(2190) - abs(get(2195)),
            get(2000) + get(2010), 'K9')
    else:
        coeffs['K9'] = MARKER_ZERO
    
    # =========================================================================
    # X10: Спроможність покривати короткострокові зобов'язання поточними активами
    # Coef_ID: Current_ratio_1
    # Group: 1 (MIN_WOE) для Big, 0 (не використовується) для Small
    # Formula Big: X1195/X1695
    # Formula Small: 0 (не використовується)
    # =========================================================================
    if zvit == 1:
        coeffs['K10'] = divide(get(1195), get(1695), 'K10')
    else:
        coeffs['K10'] = MARKER_ZERO
    
    # =========================================================================
    # X11: Спроможність обслуговування боргу доходами від основного виду діяльності
    # Coef_ID: D_Sales
    # Group: 2 (MAX_WOE)
    # Formula Big: NET_DEBT/(X2000+X2010)
    # Formula Small: NET_DEBT/X2000
    # =========================================================================
    if zvit == 1:
        coeffs['K11'] = divide(net_debt, get(2000) + get(2010), 'K11')
    else:
        coeffs['K11'] = divide(net_debt, get(2000), 'MK11')
    
    # =========================================================================
    # X12: Ефективність використання активів підприємства
    # Coef_ID: EBT_Assets
    # Group: 0 (не використовується) для Big, 1 (MIN_WOE) для Small
    # Formula Big: 0 (не використовується)
    # Formula Small: X2290/X1300
    # =========================================================================
    if zvit == 1:
        coeffs['K12'] = MARKER_ZERO
    else:
        coeffs['K12'] = divide(get(2290), get(1300), 'MK12')
    
    # =========================================================================
    # X13: Частка активів без прямого відношення до операційної діяльності
    # Coef_ID: Not_operational_items
    # Group: 2 (MAX_WOE)
    # Formula Big: (X1000+X1030+X1035+X1040+X1045+X1050+X1090+X1155+X1160+X1190)/X1300
    # Formula Small: (X1030+X1090+X1160+X1190)/X1300
    # =========================================================================
    if zvit == 1:
        num = (get(1000) + get(1030) + get(1035) + get(1040) + get(1045) +
               get(1050) + get(1090) + get(1155) + get(1160) + get(1190))
        coeffs['K13'] = divide(num, get(1300), 'K13')
    else:
        num = get(1030) + get(1090) + get(1160) + get(1190)
        coeffs['K13'] = divide(num, get(1300), 'MK13')
    
    # =========================================================================
    # X14: Період повного обороту поточних активів
    # Coef_ID: CA_turn
    # Group: 2 (MAX_WOE)
    # Formula Big: (X1195*365)/(X2000+X2010)
    # Formula Small: (X1195*365)/X2000
    # =========================================================================
    if zvit == 1:
        coeffs['K14'] = divide(get(1195) * 365, get(2000) + get(2010), 'K14')
    else:
        coeffs['K14'] = divide(get(1195) * 365, get(2000), 'MK14')
    
    # =========================================================================
    # X15: Спроможність фінансування неопераційних витрат операційним прибутком
    # Coef_ID: EBITDA_1_ie_2
    # Group: 3 (ZERO при знам.<=0) для Big, 0 (не використовується) для Small
    # Formula Big: (X2190-X2195+X2515)/max((X2250-X2220);0)
    # Formula Small: 0 (не використовується)
    # =========================================================================
    if zvit == 1:
        coeffs['K15'] = divide(
            get(2190) - abs(get(2195)) + abs(get(2515)),
            max(abs(get(2250)) - abs(get(2220)), 0), 'K15')   # [V2-B5] |2220|
    else:
        coeffs['K15'] = MARKER_ZERO
    
    # =========================================================================
    # X16: Ефективність діяльності підприємства до оподаткування
    # Coef_ID: EBT_margin
    # Group: 1 (MIN_WOE)
    # Formula Big: (X2190-X2195+X2220-X2250)/(X2000+X2010)
    # Formula Small: X2290/X2000
    # =========================================================================
    if zvit == 1:
        coeffs['K16'] = divide(
            get(2190) - abs(get(2195)) + abs(get(2220)) - abs(get(2250)),   # [V2-B5] |2220|
            get(2000) + get(2010), 'K16')
    else:
        coeffs['K16'] = divide(get(2290), get(2000), 'MK16')
    
    # =========================================================================
    # X17: Спроможність фінансування фінансових витрат валовим прибутком
    # Coef_ID: gross_profit_ie_2
    # Group: 3 (ZERO при знам.<=0)
    # Formula Big: (X2090-X2095)/max((X2250-X2220);0)
    # Formula Small: (X2000-X2050)/(X2165+X2270)
    # =========================================================================
    if zvit == 1:
        coeffs['K17'] = divide(
            get(2090) - abs(get(2095)),
            max(abs(get(2250)) - abs(get(2220)), 0), 'K17')   # [V2-B5] |2220|
    else:
        # Знаменник = |X2165+X2270| — ABS потрібен, бо комбінований стовпець
        # може містити від'ємні значення (Excel: ABS(FZ)+ABS(EV)+ABS(FH))
        # [V2-A2] п.8 Додатка 7: для форми 2-мс (F110 = 4) рядка 2270 «не передбачено» →
        #         показник не враховується (X17 = 0)
        if _f110_code(row) == '4':
            coeffs['K17'] = MARKER_ZERO
        else:
            coeffs['K17'] = divide(
                get(2000) - abs(get(2050)),
                abs(get(2270, 2165)), 'MK17')
    
    return coeffs
